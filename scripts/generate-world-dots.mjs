// Generates src/components/ui/worldMapData.ts from real Natural Earth land data.
// Usage:  npm i -D world-atlas topojson-client d3-geo
//         node scripts/generate-world-dots.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const require = createRequire(import.meta.url);

// "land-110m.json" = light, "land-50m.json" = more coastline detail (slower to generate)
const topo = require("world-atlas/land-50m.json");
const land = feature(topo, topo.objects.land);

const COLS = 210; // dots across 360° of longitude. Raise for a denser, crisper map
const LAT_N = 84; // crop: top of Greenland / Arctic islands
const LAT_S = -58; // crop: below Tierra del Fuego (no Antarctica)

const STEP = 360 / COLS; // square dots: same degree step in lon and lat
const ROWS = Math.floor((LAT_N - LAT_S) / STEP);

const rows = {};
let count = 0;

for (let r = 0; r < ROWS; r++) {
  const lat = LAT_N - (r + 0.5) * STEP;
  const offset = r % 2 ? 0.5 : 0; // staggered rows, must match the component
  const cols = [];

  for (let c = 0; c < COLS; c++) {
    const lon = -180 + (c + 0.5 + offset) * STEP;
    if (lon <= 180 && geoContains(land, [lon, lat])) cols.push(c);
  }

  // compress consecutive columns into [start, end] spans
  const spans = [];
  for (const c of cols) {
    const last = spans[spans.length - 1];
    if (last && c === last[1] + 1) last[1] = c;
    else spans.push([c, c]);
  }
  if (spans.length) {
    rows[r] = spans;
    count += cols.length;
  }
}

const out = `/* AUTO-GENERATED by scripts/generate-world-dots.mjs from Natural Earth land data. Do not edit by hand. */
export type Span = [number, number];

export const MAP_COLS = ${COLS};
export const MAP_ROWS = ${ROWS};
export const MAP_LAT_N = ${LAT_N};
export const MAP_LAT_S = ${LAT_S};
export const MAP_STEP_DEG = ${STEP};

export const WORLD_ROWS: Record<number, Span[]> = ${JSON.stringify(rows)};
`;

const target = path.resolve("src/components/ui/worldMapData.ts");
fs.writeFileSync(target, out);
console.log(`Wrote ${target}: ${ROWS} rows, ${count} land dots`);
